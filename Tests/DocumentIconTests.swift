    func testPrusaAliasesResolveTheRealRenamedInstallationAndKeepItsPath() throws {
        try withDirectory { directory in
            let bundle = directory.appendingPathComponent("Renamed Prusa.app")
            let executable = bundle.appendingPathComponent("Contents/MacOS/slicer")
            try FileManager.default.createDirectory(at: executable.deletingLastPathComponent(), withIntermediateDirectories: true)
            try Data("#!/bin/sh\nexit 0\n".utf8).write(to: executable)
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: executable.path)
            let info: [String: Any] = ["CFBundleIdentifier": "com.prusa3d.slic3r", "CFBundleName": "PrusaSlicer", "CFBundleExecutable": "slicer", "CFBundlePackageType": "APPL"]
