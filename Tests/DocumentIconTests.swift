    func testOwnedVersionTwoIconsUpgradeWithoutChangingTheDocument() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("legacy.gcode")
            let contents = Data("; generated by BambuStudio 2.4\n".utf8)
            try contents.write(to: file)
            let oldIcon = NSImage(size: NSSize(width: 32, height: 32))
            oldIcon.lockFocus(); NSColor.magenta.setFill(); NSRect(x: 0, y: 0, width: 32, height: 32).fill(); oldIcon.unlockFocus()
            XCTAssertTrue(NSWorkspace.shared.setIcon(oldIcon, forFile: file.path, options: []))
            let oldFork = try XCTUnwrap(fork(file))
            let hash = SHA256.hash(data: oldFork).map { String(format: "%02x", $0) }.joined()
            let marker = Data("v2:bambu:\(hash)".utf8)
            marker.withUnsafeBytes { _ = setxattr(file.path, "com.moraesdev.slicer-router.icon", $0.baseAddress, marker.count, 0, 0) }
            let modified = try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertNotEqual(fork(file), oldFork, "An owned icon from 1.5.0 must receive the new rendering")
            var value = [UInt8](repeating: 0, count: 256)
            let count = getxattr(file.path, "com.moraesdev.slicer-router.icon", &value, value.count, 0, 0)
            XCTAssertGreaterThan(count, 0)
            XCTAssertTrue(String(decoding: value.prefix(max(0, count)), as: UTF8.self).hasPrefix("v3:bambu:"))
            XCTAssertEqual(try Data(contentsOf: file), contents)
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, modified)
        }
    }

