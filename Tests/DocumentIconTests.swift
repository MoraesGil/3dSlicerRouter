import AppKit
import UniformTypeIdentifiers
import XCTest

final class DocumentIconTests: XCTestCase {
    func testStylesDistinguishTheSlicersAndKeepUnknownAppsNeutral() {
        XCTAssertEqual(SlicerIconStyle.style(for: .bambuStudio), .bambu)
        XCTAssertEqual(SlicerIconStyle.style(for: .orcaSlicer), .orca)
        XCTAssertEqual(SlicerIconStyle.style(for: .snapmakerOrca), .snapmaker)
        XCTAssertEqual(SlicerIconStyle.style(for: SlicerApp(bundleID: "com.prusa3d.slic3r", path: "/Synthetic/PrusaSlicer.app", name: "PrusaSlicer")), .prusa)
        XCTAssertEqual(SlicerIconStyle.style(for: SlicerApp(bundleID: "test.custom", path: "/Synthetic/Custom.app", name: "Custom")), .router)
        XCTAssertEqual(Set(SlicerIconStyle.allCases.map(\.marker)).count, SlicerIconStyle.allCases.count)
    }

    func testSmallIconsHaveDistinctPixelsAndLargerViewsKeepTheModel() throws {
        XCTAssertTrue(RouterFileIcon.usesBrandIcon(maximumSize: CGSize(width: 16, height: 16)))
        XCTAssertTrue(RouterFileIcon.usesBrandIcon(maximumSize: CGSize(width: 64, height: 64)))
        XCTAssertFalse(RouterFileIcon.usesBrandIcon(maximumSize: CGSize(width: 65, height: 65)))
        for pixels in [16, 32, 64, 512] {
            let icons = try SlicerIconStyle.allCases.map { try RouterFileIcon.png(style: $0, pixels: pixels) }
            XCTAssertEqual(Set(icons).count, icons.count)
            XCTAssertTrue(icons.allSatisfy { NSImage(data: $0)?.size == NSSize(width: pixels, height: pixels) })
        }
        XCTAssertNotNil(RouterFileIcon.logoURL, "Use the actual Router logo from the shipped app")
    }

    func testApplyingAndRemovingAnIconPreservesDocumentContents() throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        for ext in FileAssociations.extensions {
            let file = directory.appendingPathComponent("synthetic.\(ext)")
            let contents = Data("; generated by OrcaSlicer 2.4.0\nG1 X1 Y1 E1\n".utf8)
            try contents.write(to: file)
            let modified = try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .orcaSlicer))
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertEqual(try Data(contentsOf: file), contents)
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, modified)
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, modified)
            XCTAssertEqual(try Data(contentsOf: file), contents)
        }
    }

    func testBothDocumentTypesHaveAssociationTargetsWithoutGenericData() {
        XCTAssertEqual(FileAssociations.extensions, ["3mf", "gcode"])
        let types = FileAssociations.types
        XCTAssertTrue(types.contains { $0.identifier == "org.3mf.3mf" })
        XCTAssertTrue(types.contains { $0.identifier == "com.moraesdev.gcode" })
        XCTAssertEqual(Set(types.map(\.identifier)).count, types.count)
        XCTAssertFalse(types.contains { $0 == .data || $0 == .content || $0 == .plainText })
        let app = Bundle(for: Self.self).bundleURL.deletingLastPathComponent().appendingPathComponent("3dSlicerRouter.app")
        let values = try? PropertyListSerialization.propertyList(from: Data(contentsOf: app.appendingPathComponent("Contents/Info.plist")), format: nil) as? [String: Any]
        let declarations = values?["CFBundleDocumentTypes"] as? [[String: Any]] ?? []
        XCTAssertTrue(declarations.contains { ($0["LSItemContentTypes"] as? [String])?.contains("com.moraesdev.gcode") == true })
        XCTAssertTrue(declarations.allSatisfy { $0["CFBundleTypeIconFile"] as? String == "AppIcon" })
    }

    func testPersonalCustomIconsArePreservedBeforeAndAfterRouterIcons() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("personal.gcode")
            try Data("; generated by OrcaSlicer 2.4.0\n".utf8).write(to: file)
            let personal = NSImage(size: NSSize(width: 32, height: 32))
            personal.lockFocus()
            NSColor.magenta.setFill()
            NSRect(x: 0, y: 0, width: 32, height: 32).fill()
            personal.unlockFocus()
            XCTAssertTrue(NSWorkspace.shared.setIcon(personal, forFile: file.path, options: []))
            let original = fork(file)
            XCTAssertFalse(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(fork(file), original)
            XCTAssertTrue(NSWorkspace.shared.setIcon(nil, forFile: file.path, options: []))
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .orcaSlicer))
            XCTAssertTrue(NSWorkspace.shared.setIcon(personal, forFile: file.path, options: []))
            let replacement = fork(file)
            XCTAssertFalse(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(fork(file), replacement, "A stale Router marker cannot authorize removing a later personal icon")
        }
    }

    func testReadOnlyPreferencesUseConfirmedLocalChoicesAfterXattrsDisappear() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("choice.gcode")
            let contents = Data("; generated by OrcaSlicer 2.4.0\n; printer_model = Snapmaker U1\n".utf8)
            try contents.write(to: file)
            let storeDirectory = directory.appendingPathComponent("store")
            let store = Store(directory: storeDirectory)
            let foreign = FileRecord(uuid: "foreign", printerModel: nil,
                app: SlicerApp(bundleID: "com.apple.Terminal", path: "/Applications/Utilities/Terminal.app", name: "Terminal"),
                override: true, settingsHash: nil)
            XCTAssertTrue(foreign.write(to: file))
            XCTAssertNil(store.record(for: file))
            XCTAssertNil(RoutingPreferences.read(for: file, directory: storeDirectory).record)
            let foreignKnown = FileRecord(uuid: "foreign-known", printerModel: nil, app: .bambuStudio, override: true, settingsHash: nil)
            XCTAssertTrue(foreignKnown.write(to: file))
            XCTAssertNil(store.record(for: file), "Even a known slicer needs a confirmed local choice before a document can claim it as the user's preference")
            let chosen = FileRecord(uuid: "confirmed", printerModel: "Snapmaker U1", app: .bambuStudio, override: true, settingsHash: nil)
            store.save(chosen, for: file, reason: "synthetic user selection")
            store.remember(printer: "Snapmaker U1", app: .snapmakerOrca)
            let copy = directory.appendingPathComponent("local-copy.gcode")
            try FileManager.default.copyItem(at: file, to: copy)
            XCTAssertEqual(RoutingPreferences.read(for: copy, directory: storeDirectory).record?.app, .bambuStudio)
            FileRecord.remove(from: file)
            let snapshot = RoutingPreferences.read(for: file, directory: storeDirectory)
            XCTAssertEqual(snapshot.record?.app, .bambuStudio)
            XCTAssertEqual(snapshot.mappings.byModel["Snapmaker U1"], .snapmakerOrca)
            XCTAssertEqual(try RoutableDocument.read(url: file).expectedApp(record: snapshot.record, mappings: snapshot.mappings), .bambuStudio)
            XCTAssertEqual(try Data(contentsOf: file), contents)
            let missing = directory.appendingPathComponent("never-create-this-directory")
            _ = RoutingPreferences.read(for: file, directory: missing)
            XCTAssertFalse(FileManager.default.fileExists(atPath: missing.path))
            XCTAssertEqual(RoutingPreferences.directory, PreviewCache.directory.deletingLastPathComponent())
        }
    }

    func testExplicitPrinterMappingKeepsItsSelectedInstallationPath() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("mapped.gcode")
            try Data("; generated by Snapmaker Orca 2.4.1\n; printer_model = Snapmaker U1\n".utf8).write(to: file)
            var maps = Mappings()
            let beta = SlicerApp(bundleID: SlicerApp.snapmakerOrca.bundleID, path: "/Synthetic/Beta.app", name: "Snapmaker Orca")
            maps.byModel["Snapmaker U1"] = beta
            let previous = FileRecord(uuid: "u", printerModel: "Snapmaker U1", app: .snapmakerOrca, override: false, settingsHash: nil)
            XCTAssertEqual(try RoutableDocument.read(url: file).expectedApp(record: previous, mappings: maps)?.path, beta.path)
        }
    }

    func testPrusaAliasesResolveTheRealRenamedInstallationAndKeepItsPath() throws {
        try withDirectory { directory in
            let bundle = directory.appendingPathComponent("Renamed Prusa.app")
            let executable = bundle.appendingPathComponent("Contents/MacOS/slicer")
            try FileManager.default.createDirectory(at: executable.deletingLastPathComponent(), withIntermediateDirectories: true)
            try Data("#!/bin/sh\nexit 0\n".utf8).write(to: executable)
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: executable.path)
            let info: [String: Any] = ["CFBundleIdentifier": "com.prusa3d.slic3r", "CFBundleName": "PrusaSlicer", "CFBundleExecutable": "slicer", "CFBundlePackageType": "APPL"]
            try PropertyListSerialization.data(fromPropertyList: info, format: .xml, options: 0)
                .write(to: bundle.appendingPathComponent("Contents/Info.plist"))
            var suggestion = SlicerApp.prusaSlicer
            suggestion.path = bundle.path
            let actual = try XCTUnwrap(SlicerApp.installedApplication(for: suggestion))
            XCTAssertEqual(actual.bundleID, "com.prusa3d.slic3r")
            XCTAssertEqual(actual.path, bundle.path)
            let file = directory.appendingPathComponent("prusa.gcode")
            try Data("; generated by PrusaSlicer 3.0.0\n".utf8).write(to: file)
            let saved = FileRecord(uuid: "alias", printerModel: nil, app: actual, override: false, settingsHash: nil)
            XCTAssertEqual(try RoutableDocument.read(url: file).expectedApp(record: saved, mappings: Mappings()), actual)
        }
    }

    func testCachedGeometryDoesNotPreventIconRefreshAfterMappingChanges() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("cached.gcode")
            try Data("; generated by OrcaSlicer 2.4.0\n; printer_model = Snapmaker U1\n".utf8).write(to: file)
            let values = try file.resourceValues(forKeys: [.fileSizeKey, .contentModificationDateKey])
            let store = Store(directory: directory.appendingPathComponent("store"))
            var entry = Indexer.Entry(path: file.path, kind: "gcode", size: values.fileSize!, modified: values.contentModificationDate!)
            entry.embedded = true
            store.upsertCatalog(entry)
            XCTAssertTrue(store.isCatalogued(file.path, size: entry.size, modified: entry.modified))
            XCTAssertTrue(Indexer.refreshIcon(for: file, store: store))
            let oldIcon = fork(file)
            store.remember(printer: "Snapmaker U1", app: .bambuStudio)
            XCTAssertTrue(Indexer.refreshIcon(for: file, store: store))
            XCTAssertNotEqual(fork(file), oldIcon)
            XCTAssertTrue(store.isCatalogued(file.path, size: entry.size, modified: entry.modified))
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, entry.modified)
        }
    }

    private func fork(_ url: URL) -> Data? {
        let size = getxattr(url.path, "com.apple.ResourceFork", nil, 0, 0, 0)
        guard size > 0 else { return nil }
        var data = Data(count: size)
        let read = data.withUnsafeMutableBytes { getxattr(url.path, "com.apple.ResourceFork", $0.baseAddress, size, 0, 0) }
        return read == size ? data : nil
    }

    private func withDirectory(_ body: (URL) throws -> Void) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        try body(directory)
    }

    func testDefaultAssociationWaitsForBothTypesAndReportsFailure() {
        let done = expectation(description: "all association requests complete")
        var requested: [String] = []
        let types = [UTType(importedAs: "org.3mf.3mf"), UTType(importedAs: "com.moraesdev.gcode")]
        FileAssociations.makeDefault(at: URL(fileURLWithPath: "/Synthetic/Router.app"), types: types, setter: { _, type, reply in
            requested.append(type.identifier)
            reply(type.identifier == "com.moraesdev.gcode" ? NSError(domain: "synthetic", code: 1) : nil)
        }) { error in
            XCTAssertNotNil(error)
            XCTAssertEqual(requested, types.map(\.identifier))
            done.fulfill()
        }
        wait(for: [done], timeout: 3)
    }
}
