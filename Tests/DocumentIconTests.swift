    func testTheLogoInteriorUsesTheDestinationColourAtFinderSizes() throws {
        for style in SlicerIconStyle.allCases where style != .router {
            let target = style.colour.usingColorSpace(.deviceRGB)!
            let hue = target.hueComponent
            for pixels in [16, 32, 64] {
                let bitmap = try XCTUnwrap(NSBitmapImageRep(data: RouterFileIcon.png(style: style, pixels: pixels)))
                var coloured = 0
                var largestHueDistance: CGFloat = 0
                for y in (pixels / 4)..<(pixels * 3 / 4) {
                    for x in (pixels / 4)..<(pixels * 3 / 4) {
                        guard let colour = bitmap.colorAt(x: x, y: y)?.usingColorSpace(.deviceRGB),
                              colour.alphaComponent > 0.9,
                              colour.brightnessComponent > 0.25 else { continue }
                        if target.saturationComponent < 0.05 {
                            XCTAssertLessThan(colour.saturationComponent, 0.05, "The monochrome destination must remove the original green and blue")
                            coloured += 1
                            continue
                        }
                        guard colour.saturationComponent > 0.2 else { continue }
                        let distance = abs(colour.hueComponent - hue)
                        largestHueDistance = max(largestHueDistance, min(distance, 1 - distance))
                        coloured += 1
                    }
                }
                XCTAssertLessThan(largestHueDistance, 0.08,
                    "\(style) at \(pixels) px must tint the logo interior, not just its border")
                XCTAssertGreaterThan(coloured, pixels / 2, "The centre must show the destination colour")
            }
        }
    }

