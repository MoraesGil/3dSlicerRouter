    func testPersonalCustomIconsArePreservedBeforeAndAfterRouterIcons() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("personal.gcode")
            try Data("; generated by OrcaSlicer 2.4.0\n".utf8).write(to: file)
            let personal = NSImage(size: NSSize(width: 32, height: 32))
            personal.lockFocus()
            NSColor.magenta.setFill()
            NSRect(x: 0, y: 0, width: 32, height: 32).fill()
            personal.unlockFocus()
            XCTAssertTrue(NSWorkspace.shared.setIcon(personal, forFile: file.path, options: []))
            let original = fork(file)
            XCTAssertFalse(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(fork(file), original)
            XCTAssertTrue(NSWorkspace.shared.setIcon(nil, forFile: file.path, options: []))
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .orcaSlicer))
            XCTAssertTrue(NSWorkspace.shared.setIcon(personal, forFile: file.path, options: []))
            let replacement = fork(file)
            XCTAssertFalse(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(fork(file), replacement, "A stale Router marker cannot authorize removing a later personal icon")
        }
    }

    func testReadOnlyPreferencesUseConfirmedLocalChoicesAfterXattrsDisappear() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("choice.gcode")
            let contents = Data("; generated by OrcaSlicer 2.4.0\n; printer_model = Snapmaker U1\n".utf8)
            try contents.write(to: file)
            let storeDirectory = directory.appendingPathComponent("store")
            let store = Store(directory: storeDirectory)
            let foreign = FileRecord(uuid: "foreign", printerModel: nil,
                app: SlicerApp(bundleID: "com.apple.Terminal", path: "/Applications/Utilities/Terminal.app", name: "Terminal"),
                override: true, settingsHash: nil)
            XCTAssertTrue(foreign.write(to: file))
            XCTAssertNil(store.record(for: file))
            XCTAssertNil(RoutingPreferences.read(for: file, directory: storeDirectory).record)
            let foreignKnown = FileRecord(uuid: "foreign-known", printerModel: nil, app: .bambuStudio, override: true, settingsHash: nil)
            XCTAssertTrue(foreignKnown.write(to: file))
            XCTAssertNil(store.record(for: file), "Even a known slicer needs a confirmed local choice before a document can claim it as the user's preference")
            let chosen = FileRecord(uuid: "confirmed", printerModel: "Snapmaker U1", app: .bambuStudio, override: true, settingsHash: nil)
            store.save(chosen, for: file, reason: "synthetic user selection")
            store.remember(printer: "Snapmaker U1", app: .snapmakerOrca)
            let copy = directory.appendingPathComponent("local-copy.gcode")
            try FileManager.default.copyItem(at: file, to: copy)
            XCTAssertEqual(RoutingPreferences.read(for: copy, directory: storeDirectory).record?.app, .bambuStudio)
            FileRecord.remove(from: file)
            let snapshot = RoutingPreferences.read(for: file, directory: storeDirectory)
            XCTAssertEqual(snapshot.record?.app, .bambuStudio)
            XCTAssertEqual(snapshot.mappings.byModel["Snapmaker U1"], .snapmakerOrca)
            XCTAssertEqual(try RoutableDocument.read(url: file).expectedApp(record: snapshot.record, mappings: snapshot.mappings), .bambuStudio)
            XCTAssertEqual(try Data(contentsOf: file), contents)
            let missing = directory.appendingPathComponent("never-create-this-directory")
            _ = RoutingPreferences.read(for: file, directory: missing)
            XCTAssertFalse(FileManager.default.fileExists(atPath: missing.path))
            XCTAssertEqual(RoutingPreferences.directory, PreviewCache.directory.deletingLastPathComponent())
        }
    }

