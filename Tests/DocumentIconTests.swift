    func testApplyingAndRemovingAnIconPreservesDocumentContents() throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        for ext in FileAssociations.extensions {
            let file = directory.appendingPathComponent("synthetic.\(ext)")
            let contents = Data("; generated by OrcaSlicer 2.4.0\nG1 X1 Y1 E1\n".utf8)
            try contents.write(to: file)
            let modified = try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .orcaSlicer))
            XCTAssertTrue(RouterFileIcon.apply(to: file, app: .bambuStudio))
            XCTAssertEqual(try Data(contentsOf: file), contents)
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, modified)
            XCTAssertTrue(RouterFileIcon.remove(from: file))
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, modified)
            XCTAssertEqual(try Data(contentsOf: file), contents)
        }
    }

    func testBothDocumentTypesHaveAssociationTargetsWithoutGenericData() {
        XCTAssertEqual(FileAssociations.extensions, ["3mf", "gcode"])
