            try Data("; generated by PrusaSlicer 3.0.0\n".utf8).write(to: file)
            let saved = FileRecord(uuid: "alias", printerModel: nil, app: actual, override: false, settingsHash: nil)
            XCTAssertEqual(try RoutableDocument.read(url: file).expectedApp(record: saved, mappings: Mappings()), actual)
        }
    }

    func testCachedGeometryDoesNotPreventIconRefreshAfterMappingChanges() throws {
        try withDirectory { directory in
            let file = directory.appendingPathComponent("cached.gcode")
            try Data("; generated by OrcaSlicer 2.4.0\n; printer_model = Snapmaker U1\n".utf8).write(to: file)
            let values = try file.resourceValues(forKeys: [.fileSizeKey, .contentModificationDateKey])
            let store = Store(directory: directory.appendingPathComponent("store"))
            var entry = Indexer.Entry(path: file.path, kind: "gcode", size: values.fileSize!, modified: values.contentModificationDate!)
            entry.embedded = true
            store.upsertCatalog(entry)
            XCTAssertTrue(store.isCatalogued(file.path, size: entry.size, modified: entry.modified))
            XCTAssertTrue(Indexer.refreshIcon(for: file, store: store))
            let oldIcon = fork(file)
            store.remember(printer: "Snapmaker U1", app: .bambuStudio)
            XCTAssertTrue(Indexer.refreshIcon(for: file, store: store))
            XCTAssertNotEqual(fork(file), oldIcon)
            XCTAssertTrue(store.isCatalogued(file.path, size: entry.size, modified: entry.modified))
            XCTAssertEqual(try file.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate, entry.modified)
        }
    }

    private func fork(_ url: URL) -> Data? {
        let size = getxattr(url.path, "com.apple.ResourceFork", nil, 0, 0, 0)
        guard size > 0 else { return nil }
        var data = Data(count: size)
        let read = data.withUnsafeMutableBytes { getxattr(url.path, "com.apple.ResourceFork", $0.baseAddress, size, 0, 0) }
        return read == size ? data : nil
    }

    private func withDirectory(_ body: (URL) throws -> Void) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        try body(directory)
    }

    func testDefaultAssociationWaitsForBothTypesAndReportsFailure() {
        let done = expectation(description: "all association requests complete")
        var requested: [String] = []
        let types = [UTType(importedAs: "org.3mf.3mf"), UTType(importedAs: "com.moraesdev.gcode")]
        FileAssociations.makeDefault(at: URL(fileURLWithPath: "/Synthetic/Router.app"), types: types, setter: { _, type, reply in
            requested.append(type.identifier)
            reply(type.identifier == "com.moraesdev.gcode" ? NSError(domain: "synthetic", code: 1) : nil)
        }) { error in
            XCTAssertNotNil(error)
            XCTAssertEqual(requested, types.map(\.identifier))
            done.fulfill()
        }
        wait(for: [done], timeout: 3)
    }
