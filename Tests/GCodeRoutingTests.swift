import Foundation
import XCTest

final class GCodeRoutingTests: XCTestCase {
    private func document(_ content: String, check: (RoutableDocument, URL) throws -> Void) throws {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("route-\(UUID().uuidString).gcode")
        let bytes = Data(content.utf8)
        try bytes.write(to: url)
        defer { try? FileManager.default.removeItem(at: url) }
        try check(RoutableDocument.read(url: url), url)
        XCTAssertEqual(try Data(contentsOf: url), bytes)
    }
    private func record(_ app: SlicerApp, override: Bool = false) -> FileRecord {
        FileRecord(uuid: "test", printerModel: "Bambu Lab A1", app: app, override: override, settingsHash: nil)
    }
    func testGeneratorWinsPrinterAndOldAutomaticRecord() throws {
        try document("; generated by Snapmaker Orca 2.4.1\n; printer_model = Bambu Lab A1\n") { doc, _ in
            XCTAssertEqual(doc.originatingSlicer, .snapmakerOrca)
            XCTAssertEqual(doc.expectedApp(record: self.record(.bambuStudio), mappings: Mappings()), .snapmakerOrca)
        }
    }
    func testManualOverrideAndOption() throws {
        try document("; generated by OrcaSlicer 2.3.0\n") { doc, _ in
            let record = self.record(.bambuStudio, override: true)
            XCTAssertEqual(doc.expectedApp(record: record, mappings: Mappings()), .bambuStudio)
            XCTAssertEqual(doc.decide(record: record, mappings: Mappings(), optionHeld: true), .ask(.manual, suggested: .bambuStudio))
        }
    }
    func testExplicitModelMappingWinsGeneratorAndKeepsSavedPath() throws {
        try document("; generated by OrcaSlicer 2.3.0\n; printer_model = Bambu Lab A1\n") { doc, _ in
            var mappings = Mappings(); mappings.byModel["Bambu Lab A1"] = .snapmakerOrca
            let custom = SlicerApp(bundleID: SlicerApp.snapmakerOrca.bundleID, path: "/Custom/Snapmaker.app", name: "Custom")
            XCTAssertEqual(doc.expectedApp(record: self.record(custom), mappings: mappings), custom)
        }
    }
    func testNoMetadataAsksAndIgnoresOldAutomaticChoice() throws {
        try document("G1 X10 Y10\n; use OrcaSlicer someday\n") { doc, _ in
            XCTAssertNil(doc.originatingSlicer)
            XCTAssertEqual(doc.decide(record: self.record(.bambuStudio), mappings: Mappings(), optionHeld: false), .ask(.noPrinter, suggested: nil))
            XCTAssertNil(doc.expectedApp(record: self.record(.bambuStudio), mappings: Mappings()))
        }
    }
    func testHeadersCRLFBOMAndLargestThumbnail() throws {
        let content = "\u{feff}; generated by Bambu Studio 1.9\r\n; printer_model = Bambu Lab A1\r\n; thumbnail begin 1x1 4\r\n; AQ==\r\n; thumbnail end\r\n; thumbnail begin 2x2 4\r\n; Ag==\r\n; thumbnail end\r\n"
        try document(content) { doc, url in
            XCTAssertEqual(doc.originatingSlicer, .bambuStudio)
            XCTAssertEqual(doc.info.printerModel, "Bambu Lab A1")
            XCTAssertEqual(try GCode.metadata(url: url).thumbnail, Data([2]))
        }
    }
    func testDeclaredGeneratorVariants() throws {
        let cases: [(String, SlicerApp)] = [
            ("; generated by OrcaSlicer 2.2", .orcaSlicer),
            ("; generated by BambuStudio 2.0", .bambuStudio),
            ("; generated by SnapmakerOrca 2.4", .snapmakerOrca),
            ("; generated by PrusaSlicer 2.9", .prusaSlicer),
            (";Generated with Cura_SteamEngine 5.8.0", .cura),
            ("; generated by Creality Print 6.0", .crealityPrint)
        ]
        for (header, app) in cases {
            try document(header + "\n") { doc, _ in XCTAssertEqual(doc.originatingSlicer, app, header) }
        }
    }
}
